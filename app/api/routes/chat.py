# app/api/routes/chat.py
import json
import re
from typing import List, Optional
from fastapi import APIRouter, Request, HTTPException
from pydantic import BaseModel
from langchain_core.messages import HumanMessage, ToolMessage
from langgraph.errors import GraphRecursionError
from langfuse.langchain import CallbackHandler as LangfuseCallbackHandler
from langfuse import propagate_attributes, get_client
from app.api.deps import get_user_collection
from app.agent.astra_agent import AstraAgent
from app.core.config import get_settings

settings = get_settings()
router = APIRouter()

class OWSTContext(BaseModel):
    source_id: str
    base_url: str
    classes_to_remove: List[str] = []

class ChatRequest(BaseModel):
    session_id: str
    user_id: str
    model: Optional[str] = None
    query: str
    scope_filters: Optional[List[str]] = None
    owst_context: Optional[List[OWSTContext]] = None
    workspace_type: Optional[str] = "default"

class ChatResponse(BaseModel):
    response: str
    sources: List[str] = []
    macro: Optional[str] = None

@router.post("/chat/stream", response_model=ChatResponse)
async def chat_endpoint(req: ChatRequest, request: Request):
    langfuse_handler = LangfuseCallbackHandler()
    config = {
        "configurable": {"thread_id": req.session_id},
        "recursion_limit": 50,
        "callbacks": [langfuse_handler]
    }

    try:
        user_collection = get_user_collection(request, req.user_id)
  
        agent = AstraAgent(user_collection, model=req.model)
    except HTTPException as he:
        return ChatResponse(response=f"{he.detail}", sources=[], macro=None)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Database connection failed: {str(e)}")

    inputs = {
        "messages": [HumanMessage(content=req.query)],
        "workspace_type": req.workspace_type or "default",
        "scope_filters": req.scope_filters,
        "owst_context": [ctx.model_dump() for ctx in req.owst_context] if req.owst_context else None
    }

    try:
        with propagate_attributes(
            session_id=req.session_id,
            user_id=req.user_id,
            tags=[req.workspace_type or "default", f"model:{req.model or 'default'}"]
        ):
            state = await agent.graph.ainvoke(inputs, config=config)
            messages = state.get("messages", [])

            if not messages:
                raise HTTPException(status_code=500, detail="No response generated by agent.")

            final_response = messages[-1].content if messages[-1].content else ""

            astra_sources = []
            owst_url = None
            macro = None

            for msg in messages:
                if isinstance(msg, ToolMessage):
                    if msg.name in ["universal_knowledge_search", "filtered_knowledge_search"]:
                        found_sources = re.findall(r"Source:\s*(.+?)(?:\n|$)", str(msg.content))
                        clean_sources = [s.strip() for s in found_sources if s.strip() and s.strip() != 'Unknown']
                        astra_sources.extend(clean_sources)
                    elif msg.name == "owst_live_search":
                        try:
                            payload = json.loads(str(msg.content))
                            target_url = payload.get("target_url")
                            if target_url:
                                macro = f"RENDER_OWST: {target_url}"
                                owst_url = target_url
                        except Exception:
                            pass

            # STRICT PRIORITY FILTER
            if macro and owst_url:
                final_sources = [owst_url]
            else:
                cited_sources = re.findall(r'\[cite:\s*(.+?)\]', final_response)
                cited_sources = [s.strip() for s in cited_sources if s.strip()]
                if cited_sources:
                    final_sources = list(set(cited_sources))
                else:
                    final_sources = list(set(astra_sources))

            return ChatResponse(
                response=final_response,
                sources=final_sources,
                macro=macro
            )

    except GraphRecursionError:
        return ChatResponse(
            response="I reached my maximum search limit. Please try rephrasing your question.",
            sources=[],
            macro=None
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Chat execution failed: {str(e)}")
    finally:
        langfuse_client = get_client()
        langfuse_client.flush()